export const FONT_W = 6, FONT_H = 8;
/** Largeur en pixels d'un texte (s = facteur d'échelle entier). */
export const textWidth = (str: string, s = 1) => str.length * FONT_W * s - s;

export function drawText(ctx: CanvasRenderingContext2D, str: string, x: number, y: number, color: string, align: 'left' | 'center' | 'right' = 'left', s = 1) {
  const t = str.toUpperCase().replace(/[ÀÂ]/g, 'A').replace(/[ÈÊË]/g, 'E').replace(/[Ç]/g, 'C').replace(/…/g, '...');
  let cx = Math.round(align === 'center' ? x - textWidth(t, s) / 2 : align === 'right' ? x - textWidth(t, s) : x);
  ctx.fillStyle = color;
  for (const ch of t) {
    const g = G[ch] ?? G['?'];
    for (let i = 0; i < 35; i++) if (g[i] === '1') ctx.fillRect(cx + (i % 5) * s, Math.round(y) + Math.floor(i / 5) * s, s, s);
    cx += FONT_W * s;
  }
}
